-- SAMPE PostgreSQL foundation. This creates empty tables only; no MongoDB data is copied.
CREATE SCHEMA sampe;

CREATE TABLE sampe.users (
    id text PRIMARY KEY,
    mongo_id text UNIQUE,
    email text NOT NULL UNIQUE,
    password_hash text NOT NULL,
    name text,
    role text NOT NULL,
    created_at timestamptz NOT NULL
);

CREATE TABLE sampe.members (
    user_id text PRIMARY KEY,
    mongo_id text UNIQUE,
    email text NOT NULL UNIQUE,
    name text,
    picture text,
    created_at timestamptz NOT NULL
);

CREATE TABLE sampe.user_sessions (
    session_token text PRIMARY KEY,
    mongo_id text UNIQUE,
    user_id text NOT NULL REFERENCES sampe.members(user_id),
    expires_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL
);
CREATE INDEX user_sessions_expires_at_idx ON sampe.user_sessions (expires_at);
CREATE INDEX user_sessions_user_id_idx ON sampe.user_sessions (user_id);

CREATE TABLE sampe.licenses (
    id text PRIMARY KEY,
    mongo_id text UNIQUE,
    code text,
    label text NOT NULL,
    email text,
    source text NOT NULL,
    duration_days integer NOT NULL CHECK (duration_days > 0),
    created_at timestamptz NOT NULL,
    activated_at timestamptz,
    expires_at timestamptz,
    last_login_at timestamptz,
    revoked boolean NOT NULL DEFAULT false,
    owner_user_id text REFERENCES sampe.members(user_id),
    lynk_ref_id text
);
CREATE UNIQUE INDEX licenses_code_unique_idx ON sampe.licenses (code) WHERE code IS NOT NULL;
CREATE INDEX licenses_email_created_idx ON sampe.licenses (email, created_at DESC);
CREATE INDEX licenses_owner_created_idx ON sampe.licenses (owner_user_id, created_at DESC);

CREATE TABLE sampe.lynk_orders (
    ref_id text PRIMARY KEY,
    mongo_id text UNIQUE,
    message_id text NOT NULL,
    email text NOT NULL,
    name text,
    phone text,
    product text NOT NULL,
    days integer NOT NULL CHECK (days >= 0),
    created_at timestamptz NOT NULL,
    license_id text REFERENCES sampe.licenses(id),
    action text,
    status text NOT NULL
);
CREATE INDEX lynk_orders_email_created_idx ON sampe.lynk_orders (email, created_at DESC);
CREATE INDEX lynk_orders_license_id_idx ON sampe.lynk_orders (license_id);

CREATE TABLE sampe.login_attempts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mongo_id text UNIQUE,
    identifier text NOT NULL,
    count integer NOT NULL DEFAULT 0 CHECK (count >= 0),
    locked_until timestamptz
);
CREATE INDEX login_attempts_identifier_idx ON sampe.login_attempts (identifier);

CREATE TABLE sampe.kpi_config (
    id text PRIMARY KEY,
    mongo_id text UNIQUE,
    tenant_id text NOT NULL REFERENCES sampe.licenses(id),
    company_name text NOT NULL,
    month text NOT NULL CHECK (month ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
    target_sales numeric(20, 2) NOT NULL DEFAULT 0,
    budget_ads numeric(20, 2) NOT NULL DEFAULT 0,
    budget_branding numeric(20, 2) NOT NULL DEFAULT 0,
    budget_campaign numeric(20, 2) NOT NULL DEFAULT 0,
    budget_kol numeric(20, 2) NOT NULL DEFAULT 0,
    target_kol_count integer NOT NULL DEFAULT 0,
    live_team_count integer NOT NULL DEFAULT 0,
    target_live_hours numeric(12, 2) NOT NULL DEFAULT 0,
    target_live_revenue numeric(20, 2) NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL,
    CONSTRAINT kpi_config_tenant_month_unique UNIQUE (tenant_id, month)
);
CREATE INDEX kpi_config_tenant_month_desc_idx ON sampe.kpi_config (tenant_id, month DESC);

CREATE TABLE sampe.entries (
    id text PRIMARY KEY,
    mongo_id text UNIQUE,
    tenant_id text NOT NULL REFERENCES sampe.licenses(id),
    module text NOT NULL,
    date date NOT NULL,
    data jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(data) = 'object'),
    created_at timestamptz NOT NULL
);
CREATE INDEX entries_tenant_date_idx ON sampe.entries (tenant_id, date DESC);
CREATE INDEX entries_tenant_module_date_idx ON sampe.entries (tenant_id, module, date DESC);

CREATE TABLE sampe.settings (
    key text PRIMARY KEY,
    mongo_id text UNIQUE,
    merchant_key text,
    renew_url text,
    default_days integer CHECK (default_days IS NULL OR default_days IN (0, 1, 7, 30, 365)),
    extra jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(extra) = 'object')
);

-- MongoDB uses the buyer email itself as _id for this transaction lock.
CREATE TABLE sampe.lynk_email_locks (
    email text PRIMARY KEY,
    touched_at timestamptz NOT NULL
);

-- Invalid webhook attempts may not have an order, so ref_id is deliberately not a FK.
CREATE TABLE sampe.webhook_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mongo_id text UNIQUE,
    received_at timestamptz NOT NULL,
    status text NOT NULL,
    reason text NOT NULL,
    ref_id text,
    has_signature boolean NOT NULL DEFAULT false,
    body jsonb
);
CREATE INDEX webhook_logs_received_at_idx ON sampe.webhook_logs (received_at DESC);
CREATE INDEX webhook_logs_ref_id_idx ON sampe.webhook_logs (ref_id);
